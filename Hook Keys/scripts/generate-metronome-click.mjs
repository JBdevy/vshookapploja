import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const destination = path.join(root, 'native-engine', 'include', 'hook_keys', 'MetronomeClickData.hpp');
const sources = [4, 5].map((number) => ({
  number,
  source: path.join(root, 'native-engine', 'assets', 'clicks', `Click ${number}.wav`),
}));

async function readWav({ number, source }) {
  const wav = await readFile(source);
  if (wav.toString('ascii', 0, 4) !== 'RIFF' || wav.toString('ascii', 8, 12) !== 'WAVE') {
    throw new Error(`Click ${number}.wav não é um arquivo WAV válido.`);
  }

  let format = 0;
  let channels = 0;
  let sampleRate = 0;
  let bits = 0;
  let dataOffset = 0;
  let dataSize = 0;
  for (let offset = 12; offset + 8 <= wav.length;) {
    const id = wav.toString('ascii', offset, offset + 4);
    const size = wav.readUInt32LE(offset + 4);
    const payload = offset + 8;
    if (payload + size > wav.length) break;
    if (id === 'fmt ' && size >= 16) {
      format = wav.readUInt16LE(payload);
      channels = wav.readUInt16LE(payload + 2);
      sampleRate = wav.readUInt32LE(payload + 4);
      bits = wav.readUInt16LE(payload + 14);
    } else if (id === 'data') {
      dataOffset = payload;
      dataSize = size;
    }
    offset = payload + size + (size & 1);
  }

  if (![1, 3].includes(format) || channels < 1 || channels > 2 || sampleRate === 0
      || ![16, 24, 32].includes(bits) || dataSize === 0) {
    throw new Error(`Click ${number} incompatível: format=${format}, channels=${channels}, rate=${sampleRate}, bits=${bits}`);
  }

  const bytesPerSample = bits / 8;
  const frames = Math.floor(dataSize / (bytesPerSample * channels));
  const readSample = (offset) => {
    if (format === 3 && bits === 32) return wav.readFloatLE(offset);
    if (bits === 16) return wav.readInt16LE(offset) / 32768;
    if (bits === 24) return wav.readIntLE(offset, 3) / 8388608;
    return wav.readInt32LE(offset) / 2147483648;
  };
  const toPcm16 = (sample) => Math.max(-32768, Math.min(32767, Math.round(sample * 32767)));
  const left = [];
  const right = [];
  for (let frame = 0; frame < frames; frame += 1) {
    const offset = dataOffset + frame * bytesPerSample * channels;
    left.push(toPcm16(readSample(offset)));
    right.push(toPcm16(channels === 2 ? readSample(offset + bytesPerSample) : readSample(offset)));
  }
  return { number, sampleRate, frames, left, right };
}

const clicks = await Promise.all(sources.map(readWav));
const values = (samples) => samples
  .reduce((lines, value, index) => {
    if (index % 20 === 0) lines.push([]);
    lines.at(-1).push(String(value));
    return lines;
  }, [])
  .map((line) => `  ${line.join(', ')},`)
  .join('\n');

const output = `// Generated by scripts/generate-metronome-click.mjs. Do not edit manually.
#pragma once

#include <array>
#include <cstdint>

namespace hook_keys::embedded_metronome_click {

${clicks.map(({ number, sampleRate, frames, left, right }) => `inline constexpr std::uint32_t kClick${number}SampleRate = ${sampleRate};
inline constexpr std::array<std::int16_t, ${frames}> kClick${number}Left{{
${values(left)}
}};
inline constexpr std::array<std::int16_t, ${frames}> kClick${number}Right{{
${values(right)}
}};`).join('\n\n')}

} // namespace hook_keys::embedded_metronome_click
`;

await writeFile(destination, output, 'utf8');
console.log(`Generated ${path.relative(root, destination)}: ${clicks.map(({ number, frames, sampleRate }) => `Click ${number}: ${frames} stereo frames at ${sampleRate} Hz`).join('; ')}.`);
