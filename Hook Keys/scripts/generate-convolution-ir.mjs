import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'native-engine', 'assets', 'ir-hook');
const destination = path.join(root, 'native-engine', 'include', 'hook_keys', 'ConvolutionIrData.hpp');
const impulses = [
  ['room1', 'Room 1.wav'],
  ['room2', 'Room 2.wav'],
  ['hall1', 'Hall 1.wav'],
  ['hall2', 'Hall 2.wav'],
  ['rotaryOff', 'Rotary Off.wav'],
  ['rotaryOn', 'Rotary On.wav'],
];

const declarations = [];
const entries = [];
for (const [identifier, filename] of impulses) {
  const encoded = (await readFile(path.join(source, filename))).toString('base64');
  const wrapped = encoded.match(/.{1,120}/g)?.join('\n') ?? '';
  declarations.push(`inline constexpr char k${identifier}[] = R"IR(${wrapped})IR";`);
  entries.push(`  {"${filename.replace('.wav', '')}", k${identifier}},`);
}

const output = `// Generated by scripts/generate-convolution-ir.mjs. Do not edit manually.
#pragma once

#include <array>

namespace hook_keys::embedded_ir {

struct EncodedImpulse final {
  const char* name;
  const char* base64Wav;
};

${declarations.join('\n\n')}

inline constexpr std::array<EncodedImpulse, ${entries.length}> kImpulses{{
${entries.join('\n')}
}};

} // namespace hook_keys::embedded_ir
`;

await writeFile(destination, output, 'utf8');
console.log(`Generated ${path.relative(root, destination)} with ${impulses.length} convolution IRs.`);
