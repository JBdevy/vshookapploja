import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(root, '..', '..', 'motor hook keys', 'noise vinil', 'NoiseRain.wav');
const destination = path.join(root, 'native-engine', 'include', 'hook_keys', 'VinylNoiseData.hpp');
const wav = await readFile(source);
if (wav.toString('ascii', 0, 4) !== 'RIFF' || wav.toString('ascii', 8, 12) !== 'WAVE') {
  throw new Error('NoiseRain.wav não é um WAV válido.');
}

let format = 0;
let channels = 0;
let sampleRate = 0;
let bits = 0;
let dataOffset = 0;
let dataSize = 0;
for (let offset = 12; offset + 8 <= wav.length;) {
  const id = wav.toString('ascii', offset, offset + 4);
  const size = wav.readUInt32LE(offset + 4);
  const payload = offset + 8;
  if (payload + size > wav.length) break;
  if (id === 'fmt ' && size >= 16) {
    format = wav.readUInt16LE(payload);
    channels = wav.readUInt16LE(payload + 2);
    sampleRate = wav.readUInt32LE(payload + 4);
    bits = wav.readUInt16LE(payload + 14);
  } else if (id === 'data') {
    dataOffset = payload;
    dataSize = size;
  }
  offset = payload + size + (size & 1);
}
if (format !== 1 || channels !== 2 || sampleRate === 0 || ![16, 24, 32].includes(bits) || dataSize === 0) {
  throw new Error(`NoiseRain incompatível: format=${format}, channels=${channels}, rate=${sampleRate}, bits=${bits}`);
}

const bytesPerSample = bits / 8;
const frames = Math.floor(dataSize / (bytesPerSample * channels));
const readSample = (offset) => bits === 16
  ? wav.readInt16LE(offset) / 32768
  : bits === 24 ? wav.readIntLE(offset, 3) / 8388608 : wav.readInt32LE(offset) / 2147483648;
const pcm16 = [];
for (let frame = 0; frame < frames; frame += 1) {
  const offset = dataOffset + frame * bytesPerSample * 2;
  for (let channel = 0; channel < 2; channel += 1) {
    const value = Math.max(-1, Math.min(1, readSample(offset + channel * bytesPerSample)));
    pcm16.push(Math.max(-32768, Math.min(32767, Math.round(value * 32767))));
  }
}
const lines = pcm16.reduce((result, value, index) => {
  if (index % 24 === 0) result.push([]);
  result.at(-1).push(String(value));
  return result;
}, []).map((line) => `  ${line.join(', ')},`).join('\n');

await writeFile(destination, `// Generated by scripts/generate-vinyl-noise.mjs. Do not edit manually.
#pragma once

#include <array>
#include <cstdint>

namespace hook_keys::embedded_vinyl_noise {
inline constexpr std::uint32_t kSampleRate = ${sampleRate};
inline constexpr std::uint32_t kFrames = ${frames};
inline constexpr std::array<std::int16_t, ${pcm16.length}> kStereo{{
${lines}
}};
} // namespace hook_keys::embedded_vinyl_noise
`, 'utf8');
console.log(`Generated ${path.relative(root, destination)} with ${frames} stereo frames at ${sampleRate} Hz.`);
